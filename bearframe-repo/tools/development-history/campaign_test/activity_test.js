import assert from "node:assert/strict";
import {world,system} from "@minecraft/server";
import {installActivityLog,noteActivity} from "./activity_log.js";
installActivityLog();
const dim={id:"minecraft:overworld"};
const player={id:"alpha",isValid:true,location:{x:1,y:2,z:3},dimension:dim,typeId:"minecraft:player"};
const events=world.afterEvents;
events.playerBreakBlock.fire({player,brokenBlockPermutation:{type:{id:"minecraft:stone"}}});
events.playerPlaceBlock.fire({player,block:{typeId:"minecraft:stone_bricks"}});
const stack={typeId:"minecraft:coal",amount:6};
events.playerInventoryItemChange.fire({player,beforeItemStack:stack});
events.playerInventoryItemChange.fire({player,itemStack:stack});
system.scheduled[0]();
let s=JSON.parse(world.getDynamicProperty("bearframe:activity:alpha"));
assert.equal(s.totals["Blocks broken"],1);
assert.equal(s.totals["Blocks placed"],1);
assert.equal(s.totals["Items added"],undefined);
events.playerInventoryItemChange.fire({player,itemStack:stack});
events.playerDimensionChange.fire({player,toDimension:{id:"bearframe:city_orbit"},toLocation:{x:4,y:101,z:3}});
for(let i=0;i<80;i++)noteActivity(player,"Field entry","Entry "+i);
events.playerLeave.fire({playerId:player.id});
s=JSON.parse(world.getDynamicProperty("bearframe:activity:alpha"));
assert.equal(s.totals["Items added"],6);
assert.equal(s.totals["Field entry"],80);
assert.equal(s.recent.length,64);
assert.deepEqual(s.checkpoints.Travel.at,[4,101,3]);
assert.equal(world.getDynamicProperty("bearframe:activity:beta"),undefined);
noteActivity(player,"Campaign","Returned");
events.playerLeave.fire({playerId:player.id});
s=JSON.parse(world.getDynamicProperty("bearframe:activity:alpha"));
assert.equal(s.totals["Campaign"],1);
assert.equal(s.totals["Field entry"],80);
console.log("Activity log passed tracking, persistence, inventory move cancellation, bounded history, and player separation.");
