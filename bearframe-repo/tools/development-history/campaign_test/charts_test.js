import assert from "node:assert/strict";
import {picks} from "@minecraft/server-ui";
import {world} from "@minecraft/server";
import {openCharts,bearing,registerChartSite,removeChartBeacon,archiveChart} from "./route_charts.js";
import {initial,write} from "./campaign_state.js";
import {MAIN} from "./campaign_data.js";
const props=new Map();
const ov={id:"minecraft:overworld"};
const p={id:"traveler-map",dimension:ov,location:{x:0,y:70,z:0},isValid:true,sendMessage(){},
 getDynamicProperty:k=>props.get(k),setDynamicProperty:(k,v)=>props.set(k,v)};
assert.equal(bearing([0,0,0],[0,0,-100]),0);
assert.equal(bearing([0,0,0],[100,0,0]),2);
assert.equal(bearing([0,0,0],[-100,0,0]),6);
assert.equal(bearing([0,0,0],[80,0,80]),3);
const state=initial();state.chapter=0;write(p,state);
registerChartSite("maintenance_relay",ov.id,{x:36,y:70,z:5},"beacon");
picks.push(0,0,0,0);
await openCharts(p);
let route=JSON.parse(props.get("bearframe:tracked_chart"));
assert.equal(route.status,"beacon");
assert.deepEqual(route.p,[36,70,5]);
removeChartBeacon("maintenance_relay",ov.id,{x:36,y:70,z:5});
registerChartSite("maintenance_relay",ov.id,{x:41,y:70,z:8});
state.sites.maintenance_relay=[41,71,8];state.chapter=1;
state.facts["read:maintenance_relay"]=1;
archiveChart(p,"main",0,MAIN[0],state);
state.sites.maintenance_relay=[88,71,9];
write(p,state);
picks.push(1,0,0,0);
await openCharts(p);
route=JSON.parse(props.get("bearframe:tracked_chart"));
assert.equal(route.status,"visited");
assert.deepEqual(route.p,[41,71,8]);
assert.equal(props.has("bearframe:quest_charts"),true);
console.log("Passed bearing calculation, survey-beacon tracking, archive route snapshot, and returning to the original site after a later visit elsewhere.");
